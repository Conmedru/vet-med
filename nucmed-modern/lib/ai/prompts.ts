export const PROCESSING_PROMPT_VERSION = "v4.0-fidelity";

function rubricList(kind: RubricKind): string {
  return getRubricsByKind(kind)
    .filter((r) => isAiAssignable(r.slug))
    .map((r) => `- ${r.slug} — ${r.name}: ${r.description}`)
    .join("\n");
}

