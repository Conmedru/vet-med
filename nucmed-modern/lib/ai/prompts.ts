/**
 * Length budget for the content: a short teaser stays a short note (lib/ai/fidelity.ts
 * rejects anything longer than ×3 of a source under 1500 chars).
 */
export function contentLengthBudget(sourceChars: number): number {
  if (sourceChars < 1500) return Math.max(400, Math.round(sourceChars * 2));
  return Math.round(sourceChars * 2.5);
}

export function buildArticleProcessingUserPrompt(input: {
  sourceName: string;
  titleOriginal: string;
  contentOriginal?: string | null;
  excerptOriginal?: string | null;
}): string {
  const source = input.contentOriginal || input.excerptOriginal || "";
  const sourceChars = source.replace(/<[^>]+>/g, " ").replace(/\s+/g, " ").trim().length;
  const budget = contentLengthBudget(sourceChars);
  const shape =
    sourceChars < 1000
      ? "Это короткий анонс: content — 1–2 абзаца без заголовков ##, только то, что сказано в анонсе."
      : "content — пересказ без добавлений; заголовки ## только если для них есть материал.";
  return `Обработай следующую статью как редакционный пересказ внешней публикации. Ты не автор исследования и не участник работы. Не используй первое лицо и всегда атрибутируй выводы авторам или источнику.

ОБЪЁМ: исходный текст — ${sourceChars} знаков. content — не больше ${budget} знаков. ${shape}

ИСТОЧНИК: ${input.sourceName}

ЗАГОЛОВОК:
${input.titleOriginal}

СОДЕРЖАНИЕ:
${source || "Содержание недоступно"}`;
}

