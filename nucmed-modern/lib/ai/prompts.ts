export function buildArticleProcessingUserPrompt(input: {
  sourceName: string;
  titleOriginal: string;
  contentOriginal?: string | null;
  excerptOriginal?: string | null;
}): string {
  return `Обработай следующую статью как редакционный пересказ внешней публикации. Ты не автор исследования и не участник работы. Не используй первое лицо и всегда атрибутируй выводы авторам или источнику.

ИСТОЧНИК: ${input.sourceName}

ЗАГОЛОВОК:
${input.titleOriginal}

СОДЕРЖАНИЕ:
${input.contentOriginal || input.excerptOriginal || "Содержание недоступно"}`;
}
