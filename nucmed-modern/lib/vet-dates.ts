/** weekday: 0 = Sunday … 6 = Saturday; nth: 1..4, or -1 for the last one in the month */
type FloatingDate = { month: number; weekday: number; nth: number; title: string };

const FLOATING_DATES: FloatingDate[] = [
  { month: 5, weekday: 6, nth: 2, title: "Всемирный день мигрирующих птиц" },
  { month: 10, weekday: 6, nth: 2, title: "Всемирный день мигрирующих птиц" },
  { month: 10, weekday: 5, nth: 2, title: "Международный день ветеринарной медсестры" },
  { month: 11, weekday: 4, nth: 2, title: "Всемирный день курицы" },
];

function floatingDay(year: number, { month, weekday, nth }: FloatingDate): number {
  if (nth > 0) {
    const firstWeekday = new Date(Date.UTC(year, month - 1, 1)).getUTCDay();
    return 1 + ((weekday - firstWeekday + 7) % 7) + (nth - 1) * 7;
  }
  const lastDay = new Date(Date.UTC(year, month, 0));
  return lastDay.getUTCDate() - ((lastDay.getUTCDay() - weekday + 7) % 7);
}

const pad = (n: number) => String(n).padStart(2, "0");

/** Memorable dates of a month, monthKey = YYYY-MM */
export function getVetDatesForMonth(monthKey: string): VetDate[] {
  const [year, month] = monthKey.split("-").map(Number);
  const dates: VetDate[] = [
    ...FIXED_DATES.filter(([m]) => m === month).flatMap(([, day, titles]) =>
      titles.map((title) => ({ date: `${monthKey}-${pad(day)}`, title }))
    ),
    ...FLOATING_DATES.filter((f) => f.month === month).map((f) => ({
      date: `${monthKey}-${pad(floatingDay(year, f))}`,
      title: f.title,
    })),
  ];
  return dates.sort((a, b) => a.date.localeCompare(b.date));
}
